"""
Example 04 -- Fixed-point effects, modelled bit-true.

A: coefficient word length vs achieved stopband attenuation (~6 dB per bit).
B: rounding-mode bias after requantisation.
C: zero-input limit cycle in a fixed-point biquad (the float filter decays to 0).
D: accumulator sizing and $readmemh export of FIR taps for the FPGA stage.
"""
import os

import numpy as np

from _common import FIG_DIR, plt, save
from dspkit import core, fir, fixed as fx, iir

rng = np.random.default_rng(0)

# --- A. coefficient quantisation
h = fir.remez(63, [0, 0.2, 0.28, 1], [1, 0], [1, 10])
bits = np.arange(8, 25)
att = []
for W in bits:
    q = fx.QFormat(1, W - 1)
    hq = fx.to_real(fx.quantize(h, q), q)
    f, H = core.freqz(hq, 1, 8192)
    att.append(-np.max(core.mag_db(H)[f >= 0.28]))
f, H = core.freqz(h, 1, 8192)
ideal = -np.max(core.mag_db(H)[f >= 0.28])
fig, ax = plt.subplots(1, 2, figsize=(9, 3.2))
ax[0].plot(bits, att, "o-", ms=3, label="quantised taps")
ax[0].axhline(ideal, ls="--", c="k", lw=0.8, label=f"float design ({ideal:.0f} dB)")
ax[0].set(xlabel="coefficient word length W (Q1.W-1)", ylabel="stopband attenuation (dB)",
          title="Coefficient bits set the stopband floor")
ax[0].legend(fontsize=7)
for W in (8, 12, 16):
    q = fx.QFormat(1, W - 1)
    f, H = core.freqz(fx.to_real(fx.quantize(h, q), q), 1, 8192)
    ax[1].plot(f, core.mag_db(H), label=f"{W}-bit taps")
ax[1].set(xlabel="f / Nyquist", ylabel="dB", ylim=(-120, 5), title="63-tap Remez lowpass")
ax[1].legend(fontsize=7)
save(fig, "04_coeff_wordlength.png")

# --- B. rounding bias
v = rng.integers(-2 ** 20, 2 ** 20, 200_000)
print("Requantise by 8 bits: mean error in output LSBs")
for mode in ("floor", "trunc", "round", "convergent"):
    err = fx.round_shift(v, 8, mode) - v / 2 ** 8
    print(f"  {mode:10s} mean {err.mean():+.4f}  rms {err.std():.4f}")

# --- C. limit cycle: high-Q resonator, zero input, small initial state
r, th = 0.99, 0.3 * np.pi
sec = np.array([1.0, 0, 0, 1.0, -2 * r * np.cos(th), r * r])
q_c, q_io = fx.QFormat(2, 14), fx.QFormat(1, 15)
c = fx.quantize(sec, q_c)
NL = 2000
x0 = np.zeros(NL, dtype=np.int64)
y_fix, _ = fx.biquad_fixed(x0, c, q_c.n, q_io, "round", state=(0, 0, 3000, 0))
# float reference with the same initial output state y[-1] (explicit recursion)
yf = np.zeros(NL)
y1, y2 = 3000 / 2 ** 15, 0.0
for n in range(NL):
    yn = -sec[4] * y1 - sec[5] * y2
    yf[n] = yn
    y2, y1 = y1, yn
fig, ax = plt.subplots(figsize=(9, 3))
ax.plot(fx.to_real(y_fix, q_io) * 2 ** 15, label="Q1.15, round-to-nearest")
ax.plot(yf * 2 ** 15, "--", label="float")
ax.set(xlabel="n", ylabel="output (LSBs of Q1.15)", ylim=(-30, 30), xlim=(400, NL),
       title="Zero-input limit cycle: fixed point never reaches 0")
ax.legend(fontsize=7)
save(fig, "04_limit_cycle.png")
print("limit-cycle amplitude (LSB):", np.max(np.abs(y_fix[-200:])), " float:", np.max(np.abs(yf[-200:])) * 2 ** 15)

# --- D. accumulator sizing + export
h_mem = fir.firwin(31, 0.25)
qh = fx.QFormat(1, 15)
hc = fx.quantize(h_mem, qh)
need = fx.fir_acc_bits(hc, 16)
crude = 16 + 16 + int(np.ceil(np.log2(len(hc))))
print(f"31-tap FIR, 16b x 16b: exact worst-case accumulator {need} bits (crude bound {crude})")
path = os.path.join(FIG_DIR, "..", "fir31_q15.mem")
fx.write_mem(path, hc, 16, comment="31-tap lowpass fc=0.25 Nyquist, Q1.15, generated by dspkit")
print("wrote", os.path.normpath(path))

# Golden vectors for an HDL testbench: input codes and expected output codes
xc = fx.quantize(0.9 * rng.uniform(-1, 1, 256), fx.QFormat(1, 15))
yc = fx.fir_fixed(xc, hc, 15, 15, fx.QFormat(1, 15), rounding="round")
fx.write_mem(os.path.join(FIG_DIR, "..", "fir31_x.mem"), xc, 16)
fx.write_mem(os.path.join(FIG_DIR, "..", "fir31_y_expected.mem"), yc, 16)
print("SQNR of the 16-bit FIR vs float:", round(fx.sqnr_db(np.convolve(fx.to_real(xc, 15), h_mem)[:256], fx.to_real(yc, 15)), 1), "dB")
